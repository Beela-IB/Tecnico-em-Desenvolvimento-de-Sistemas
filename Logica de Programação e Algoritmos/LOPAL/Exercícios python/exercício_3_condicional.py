diasemana = int(input("Digite um número: "))

if(diasemana == 1):
    print("Domingo")
elif(diasemana == 2):
    print("Segunda-feira")
elif(diasemana == 3):
    print("Terça-feira")
elif(diasemana == 4):
    print("Quarta-feira")
elif(diasemana == 5):
    print("Quinta-feira")
elif(diasemana == 6):
    print("Sexta-feira")
elif(diasemana == 7):
    print("Sábado")
else:
    print("Dia inválido")